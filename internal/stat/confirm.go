package stat

// SideConfirm считает, сколько подряд идущих сэмплов держится одна и та же
// сторона: смена стороны (или её отсутствие) сбрасывает счётчик.
//
// Нужен там, где сырой сигнал - живой снимок момента (имбаланс стакана,
// стены) и может флипнуться от одной перевыставленной/снятой заявки. Без
// счётчика устойчивости такой сигнал в композите ничем не отличается от
// секундного шума: "Потенциал" мигал бы на каждый чих стакана вместо того,
// чтобы отражать реально держащийся перекос. Тот же принцип, что confirm()
// в internal/strategy/anomaly (окно подтверждения аномалии), просто для
// стороны сигнала, а не для его уровня.
//
// Не привязан к конкретному типу стороны (order.SideType и т.п.) - что
// считать "стороной", решает вызывающий код, здесь только счётчик.
type SideConfirm struct {
	side   string
	streak int
}

// Update - новый сэмпл. newSide="" означает "сейчас стороны нет вообще"
// (например, ни одной стены не найдено, имбаланс не выражен) - тоже
// сбрасывает счётчик, а не оставляет прежнюю сторону висеть по инерции.
func (c *SideConfirm) Update(newSide string) {
	if newSide != c.side {
		c.side = newSide
		c.streak = 0
	}
	if newSide != "" {
		c.streak++
	}
}

// Confirmed - сторона и true, если она продержалась минимум minStreak
// сэмплов подряд (включая самый свежий); иначе "" и false.
func (c *SideConfirm) Confirmed(minStreak int) (string, bool) {
	if c.side != "" && c.streak >= minStreak {
		return c.side, true
	}
	return "", false
}
